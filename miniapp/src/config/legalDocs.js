import { tenantBrandConfig } from './brand.config'

/** 文本里的 {{school}} / {{platform}} / {{contact}} 在渲染时替换为租户品牌配置。 */
export function fillPlaceholders(text) {
  const brand = tenantBrandConfig || {}
  const school = brand.schoolName || brand.schoolShortName || '学校'
  const platform = brand.platformName || '本平台'
  const contact = brand.supportPhone || '学校学生工作部门或信息中心'
  return String(text)
    .replace(/\{\{school\}\}/g, school)
    .replace(/\{\{platform\}\}/g, platform)
    .replace(/\{\{contact\}\}/g, contact)
}

