/**
 * 新手引导注册表（PC-PAGE-GUIDE）。
 *
 * 定位：业务页首次进入时自动弹出的 3-5 步说明，由 AppPageGuide 消费。
 * 与帮助中心任务卡（helpContent.js / graduationHelpCards.js）的分工：
 *   - 引导（本文件）：老师第一次进这页时的「这页是干嘛的、我该先做哪一步」，短、只讲当前页；
 *   - 任务卡：老师带着具体问题去查的「照着做」步骤，长、含字段与 FAQ。
 * 两者不互相替代，也不复制对方内容。
 *
 * 铁律：
 *   1) 文案只描述系统真实存在的能力与状态，状态名一律用页面上老师看得到的中文
 *      （对应枚举见 modules/graduation/constants/*.js 与 backend/app/models/graduation.py）；
 *   2) 不写「即将上线」「敬请期待」，待施工功能不进引导；
 *   3) version 改版即 +1，老师会自动重看一次（AppPageGuide 按版本比对，不需清库）；
 *   4) step 只有 title / description / image 三个字段（AppStepGuide 的 API），image 暂缺素材统一留空。
 *
 * ★ 引导不是主力，别往里堆信息 —— 2026-07-16 外部调研结论（证据见
 *   docs/03-业务模块设计/毕业设计中心/施工包/外部对标证据/）：
 *   - 约 7 成用户在第一步就关掉引导（Pendo 平台数据），NN/g 建议「能不做就不做」；
 *   - 完成率随步数陡降：2-4 步最高，≤8 步尚可，9 步以上崩溃 —— 故本文件硬性限制每个引导 ≤4 步；
 *   - 【最重要】任何关键信息都不能只存在于引导里。老师真正会看到的是页面上的空状态提示、
 *     常驻流程图和字段旁的常驻说明；引导只做「这页是干嘛的」的一次性开场白。
 *   写引导时的自检：这条信息如果老师跳过引导就永远看不到，会不会出事？会，就说明它不该只写在这里。
 */

/** 偏好键前缀：与后端 t_user_preference.pref_key 约定的 <域>.<用途> 一致 */
export function guidePrefKey(guideKey) {
  return `guide.${guideKey}`
}

